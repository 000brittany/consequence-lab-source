"""World extension contract. Experiment logging does not interpret domain state."""
from typing import Protocol


class World(Protocol):
    name: str

    def validate(self, state: dict, agents: list[str]) -> None: ...
    def observe(self, state: dict, actor: str) -> dict: ...
    def resource_names(self, state: dict, actor: str) -> list[str]: ...
    def inspect(self, state: dict, actor: str, path: str) -> dict | None: ...
    def apply(self, state: dict, actor: str, resource: str, arguments: dict) -> dict: ...
    def add_task(self, state: dict, actor: str, task_id: str, payload: dict) -> None: ...
    def task_complete(self, state: dict, actor: str, payload: dict) -> bool: ...
    def measure(self, state: dict) -> dict: ...


class ScheduledWorld(World, Protocol):
    """Optional hooks: old worlds retain their original runner semantics.

    Event handlers apply deterministic changes to a staged aggregate. The runner
    records full snapshots, and the independent auditor reapplies the same rule
    to verify the entire transition. Reads return a tool projection plus a
    separate investigator receipt, or None for the ordinary artifact fallback.
    """
    def model_tools(self) -> list[dict]: ...
    def normalize_action(self, submitted: dict) -> dict: ...
    def visible_time(self, state: dict) -> int: ...
    def read(self, state: dict, actor: str, arguments: dict) -> tuple | None: ...
    def task_status(self, state: dict, actor: str, payload: dict) -> str: ...
    def validate_action(self, state: dict, actor: str, action: dict) -> None: ...
    def next_event(self, aggregate: dict) -> dict | None: ...
    def apply_event(self, aggregate: dict, event: dict) -> dict: ...
    def finish_decision(self, before: dict, after: dict, actor: str, action: dict | None,
                        error: dict | None, proposals: list, result: dict | None) -> dict: ...
